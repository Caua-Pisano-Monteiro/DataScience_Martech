"""### O **ROI** (Retorno sobre o Investimento) em marketing é calculado da seguinte forma


### **fórmula:**

### ROI = [(Receita gerada − Custos totais) / Custos totais] × 100
"""

campanha['roi'] = ((campanha['receita'] - campanha['custo'])/campanha['custo'])
campanha

